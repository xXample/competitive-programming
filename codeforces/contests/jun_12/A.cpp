const int MOD = 1e9 + 7;
const int INF = 1e9;
const ll LINF = 1e18;

void solve() {
    int n;
    cin >> n;
    vi h(n);

    int small = 7;
    int large = 0;
    for (auto &i : h) {
        cin >> i;
        small = min(small, i);
        large = max(large, i);
    }
    cout << large - small + 1 << '\n';
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t = 1;
    cin >> t;
    while (t--) {
        solve();
    }

    return 0;
}